"""Generate six clean scientific PNG figures from experiment results."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))
from common import FIGURES, RESULTS, ensure_dirs, read_json  # noqa: E402


def main() -> int:
    ensure_dirs()
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib no instalado: figuras NO MEDIDA")
        return 3
    plt.rcParams.update({"figure.facecolor": "white", "axes.facecolor": "white", "font.size": 9})
    with (RESULTS / "detection_cases.csv").open(encoding="utf-8") as h: detection = list(csv.DictReader(h))
    with (RESULTS / "idempotency.csv").open(encoding="utf-8") as h: idem = list(csv.DictReader(h))
    with (RESULTS / "containment_trials.csv").open(encoding="utf-8") as h: containment = list(csv.DictReader(h))
    with (RESULTS / "backend_pipeline_latency.csv").open(encoding="utf-8") as h: backend_latency = list(csv.DictReader(h))
    with (RESULTS / "n8n_e2e_latency.csv").open(encoding="utf-8") as h: n8n_latency = list(csv.DictReader(h))
    metrics = read_json(RESULTS / "detection_metrics.json"); integrity = read_json(RESULTS / "audit_integrity.json")
    catalog = [r for r in detection if r["expected_positive"] == "True"]
    fig, ax = plt.subplots(); ax.bar(["Positivos", "Negativos"], [len(catalog), len(detection)-len(catalog)], color=["#2563eb", "#94a3b8"]); ax.set_title("Figura 1. Casos HIBP"); fig.tight_layout(); fig.savefig(FIGURES / "01_dataset_cases.png", dpi=300); plt.close(fig)
    fig, ax = plt.subplots(); ax.imshow([[metrics["TP"], metrics["FN"]], [metrics["FP"], metrics["TN"]]], cmap="Blues"); ax.set_xticks([0,1], ["Pred. positivo", "Pred. negativo"]); ax.set_yticks([0,1], ["Real positivo", "Real negativo"]); ax.set_title("Figura 2. Matriz de confusión"); fig.tight_layout(); fig.savefig(FIGURES / "02_confusion_matrix.png", dpi=300); plt.close(fig)
    severity = {"baja": 0, "media": 0, "alta": 0, "critica": 0}
    # Severity is generated by the dedicated rule script when available.
    severity_path = RESULTS / "severity_distribution.csv"
    summary_path = RESULTS / "severity_summary.json"
    if summary_path.exists():
        summary = read_json(summary_path)
        for key in severity: severity[key] = int(summary[key]["count"])
    fig, ax = plt.subplots(); ax.bar(list(severity), list(severity.values()), color=["#94a3b8", "#facc15", "#f97316", "#dc2626"]); ax.set_title("Figura 3. Severidad"); fig.tight_layout(); fig.savefig(FIGURES / "03_severity.png", dpi=300); plt.close(fig)
    fig, ax = plt.subplots(); ax.bar([r["case_id"] for r in idem], [float(r["duplicate_suppression_rate"]) for r in idem], color="#0f766e"); ax.set_ylim(0,1.05); ax.tick_params(axis="x", rotation=90); ax.set_title("Figura 4. Supresión de duplicados"); fig.tight_layout(); fig.savefig(FIGURES / "04_duplicate_suppression.png", dpi=300); plt.close(fig)
    fig, ax = plt.subplots();
    backend_values = [float(r["total_e2e_ms"]) for r in backend_latency if r.get("total_e2e_ms") not in ("", "NA")]
    n8n_values = [float(r["total_e2e_ms"]) for r in n8n_latency if r.get("result") == "success"]
    ax.boxplot([backend_values, n8n_values], tick_labels=["Backend pipeline", "n8n E2E"]); ax.set_ylabel("ms"); ax.set_title("Figura 5. Latencia comparativa descriptiva"); fig.tight_layout(); fig.savefig(FIGURES / "05_latency.png", dpi=300); plt.close(fig)
    fig, ax = plt.subplots(); ax.bar(["Antes", "Tamper", "Restaurado"], [int(integrity["before_tamper_ok"]), int(integrity["after_tamper_ok"]), int(integrity["restored_ok"])], color=["#16a34a", "#dc2626", "#16a34a"]); ax.set_ylim(0,1.1); ax.set_title("Figura 6. Integridad de auditoría"); fig.tight_layout(); fig.savefig(FIGURES / "06_audit_integrity.png", dpi=300); plt.close(fig)
    print("figures_generated=6")
    return 0


if __name__ == "__main__": raise SystemExit(main())
